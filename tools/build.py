"""Create and verify the standalone Veyra release."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
MODULES = (
    ("minigames.lua", "__startMinigames()"),
    ("parry_learning.lua", "__learning"),
    ("attack_catalog.lua", "__catalog"),
    ("parry_timing.lua", "__timing"),
    ("attack_inference.lua", "__inference"),
    ("attack_seed.lua", "__seed"),
)


def build(check=False):
    source = ROOT / "src"
    runtime = (source / "runtime.lua").read_text(encoding="utf-8")
    modules = {name: (source / name).read_text(encoding="utf-8") for name, _ in MODULES}
    for name, replacement in MODULES:
        dependency = f'loadstring(readfile("Veyra/src/{name}"),"{name}")()'
        if runtime.count(dependency) != 1:
            raise ValueError(f"Expected exactly one dependency: {name}")
        runtime = runtime.replace(dependency, replacement)

    release = (
        "-- Generated by tools/build.py; edit src/ instead.\n"
        'if not isfolder("Veyra") then makefolder("Veyra") end\n'
        "local function __startMinigames()\n" + modules["minigames.lua"] + "\nend\n"
        + "".join(
            f"local {symbol}=(function()\n{modules[name]}\nend)()\n"
            for name, symbol in MODULES[1:]
        )
        + runtime
    )
    data = release.encode("utf-8")
    output = ROOT / "main.lua"
    if check:
        if not output.is_file() or output.read_bytes() != data:
            raise SystemExit("main.lua is out of date; run python tools/build.py")
        print(f"PASS: main.lua matches src/ ({len(data)} bytes)")
    else:
        output.write_bytes(data)
        print(f"Built main.lua ({len(data)} bytes)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify output without writing")
    build(check=parser.parse_args().check)
