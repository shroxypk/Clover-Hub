"""Build Veyra's standalone release."""
import argparse
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def build(check=False):
    source = ROOT / "src"
    runtime = (source / "runtime.lua").read_text(encoding="utf-8")
    minigames = (source / "minigames.lua").read_text(encoding="utf-8")
    quest = (source / "quest_assist.lua").read_text(encoding="utf-8") if (source / "quest_assist.lua").exists() else ""
    dependency = 'loadstring(readfile("Veyra/src/minigames.lua"),"minigames.lua")()'
    if runtime.count(dependency) != 1:
        raise ValueError("Expected exactly one minigame dependency")
    quest_dep = 'loadstring(readfile("Veyra/src/quest_assist.lua"),"quest_assist.lua")()'
    if quest and runtime.count(quest_dep) != 1:
        raise ValueError("Expected exactly one quest dependency")
    parry_dep = 'loadstring(readfile("Veyra/src/auto_parry.lua"),"auto_parry.lua")()'
    if (source / "auto_parry.lua").exists():
        if runtime.count(parry_dep) != 1:
            raise ValueError("Expected exactly one parry dependency")
        parry = (source / "auto_parry.lua").read_text(encoding="utf-8")
        for name in ("parry_profiles", "parry_math"):
            dependency_text = f'loadstring(readfile("Veyra/src/{name}.lua"),"{name}.lua")()'
            if parry.count(dependency_text) != 1:
                raise ValueError(f"Expected exactly one {name} dependency")
            module = (source / f"{name}.lua").read_text(encoding="utf-8")
            parry = parry.replace(dependency_text, "(function()\n" + module + "\nend)()")
        runtime = runtime.replace(parry_dep, "local function __startParry()\n" + parry + "\nend\n__startParry()")
    bundled = (
        "-- Generated by tools/build.py; edit src/ instead.\n"
        "local function __startMinigames()\n" + minigames + "\nend\n"
        + runtime.replace(dependency, "__startMinigames()").replace(quest_dep, "local function __startQuestAssist()\n" + quest + "\nend\n__startQuestAssist()")
    ).encode("utf-8")
    output = ROOT / "main.lua"
    if check:
        if not output.is_file() or output.read_bytes() != bundled:
            raise SystemExit("main.lua is stale; run python tools/build.py")
        print(f"PASS: main.lua matches sources ({len(bundled)} bytes)")
    else:
        output.write_bytes(bundled)
        print(f"Built main.lua ({len(bundled)} bytes)")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true", help="Verify output without writing")
    build(check=parser.parse_args().check)
