"""Export inspected animation metadata to src/attack_seed.lua."""
import argparse
import json
import os
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
PLACE_ID = 8248288152


def lua(value):
    if isinstance(value, dict):
        return "{" + ",".join(f"[{lua(k)}]={lua(v)}" for k, v in sorted(value.items())) + "}"
    if isinstance(value, list):
        return "{" + ",".join(lua(v) for v in value) + "}"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    return repr(value)


def main():
    base = os.environ.get("LOCALAPPDATA")
    default = Path(base) / f"Madium/Workspace/Veyra/attack_catalog_{PLACE_ID}.json" if base else None
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("source", nargs="?", type=Path, default=default, help="Captured catalog JSON")
    args = parser.parse_args()
    if args.source is None:
        parser.error("Specify a catalog JSON file")
    data = json.loads(args.source.read_text(encoding="utf-8"))
    if data.get("version") != 1 or data.get("placeId") != PLACE_ID:
        raise ValueError("Incompatible catalog version or place ID")
    lines = [
        "-- Generated by tools/export_seed.py; marker metadata, not verified combat results.",
        f"return {{placeId={PLACE_ID},records={{",
    ]
    for key, record in sorted(data["records"].items()):
        if not key.isdigit():
            raise ValueError(f"Invalid animation ID: {key}")
        lines.append(f" [{lua(key)}]={lua(record)},")
    lines.append("}}")
    (ROOT / "src/attack_seed.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"Exported {len(data['records'])} animation records")


if __name__ == "__main__":
    main()
