"""Convert the executor's read-only animation catalog to a bundled Luau seed."""
import json
import os
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parent


def lua(value):
    if isinstance(value, dict):
        return "{" + ",".join(f"[{lua(k)}]={lua(v)}" for k, v in sorted(value.items())) + "}"
    if isinstance(value, list):
        return "{" + ",".join(lua(v) for v in value) + "}"
    if isinstance(value, str):
        return json.dumps(value, ensure_ascii=False)
    if value is None:
        return "nil"
    if isinstance(value, bool):
        return "true" if value else "false"
    return repr(value)


source = Path(sys.argv[1]) if len(sys.argv) > 1 else (
    Path(os.environ["LOCALAPPDATA"]) / "Madium/Workspace/CloverRPG/attack_catalog_8248288152.json"
)
data = json.loads(source.read_text(encoding="utf-8"))
assert data["version"] == 1 and data["placeId"] == 8248288152
lines = ["-- Generated by export_seed.py from animation assets; not combat success labels.",
         "return {placeId=8248288152,records={"]
for key, record in sorted(data["records"].items()):
    assert key.isdigit()
    lines.append(f" [{lua(key)}]={lua(record)},")
lines.append("}}")
(ROOT / "attack_seed.lua").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"Exported {len(data['records'])} animation records")
